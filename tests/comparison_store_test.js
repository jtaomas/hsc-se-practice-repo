'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {Readable}=require('node:stream');
const {createStore}=require('../server/marking-store');
const records=new Map();let clock=100000,version=0;
const user=n=>crypto.createHash('sha256').update('user'+n).digest('hex');
const digest=n=>crypto.createHash('sha256').update('input'+n).digest('hex');
const blob={async get(p){const r=records.get(p);return r?{statusCode:200,stream:Readable.from([r.text]),blob:{etag:r.etag}}:null},async put(p,text,opt){const old=records.get(p);if(old&&(!opt.allowOverwrite||opt.ifMatch!==old.etag))throw new Error('Precondition failed');records.set(p,{text,etag:String(++version)})}};
const make=()=>createStore({kind:'comparison',blob:async()=>blob,now:()=>clock,limits:{perUser:2,site:3}});
const result={status:'complete',summary:'Synthetic report.',profiles:[],comparisons:[],statistics:{},audit:{}};
(async()=>{
 const a=make(),b=make();
 const jobs=await Promise.all([a.getOrReserve(user(1),digest(1)),b.getOrReserve(user(1),digest(1))]);
 assert.equal(jobs.filter(j=>j.state==='reserved').length,1);assert.equal(jobs.filter(j=>j.state==='busy').length,1);
 const job=jobs.find(j=>j.state==='reserved');await a.finish(user(1),digest(1),job.leaseId,result);
 assert.deepEqual(await b.getCached(user(1),digest(1)),result);assert.equal(await b.getCached(user(2),digest(1)),null);
 assert([...records.keys()].every(p=>p.startsWith('comparison/v1/')));
 const marker=createStore({blob:async()=>blob,now:()=>clock});assert.equal(await marker.getCached(user(1),digest(1)),null);
 const second=await a.getOrReserve(user(1),digest(2));await a.fail(user(1),digest(2),second.leaseId,{code:'provider_error'});
 await assert.rejects(a.getOrReserve(user(1),digest(3)),e=>e.code==='quota_exceeded');
 const third=await a.getOrReserve(user(2),digest(1));
 await assert.rejects(a.getOrReserve(user(3),digest(1)),e=>e.code==='quota_exceeded');
 await assert.rejects(a.finish(user(2),digest(1),third.leaseId,{...result,sourceAnswers:'secret'}),/unexpected source/);
 await a.finish(user(2),digest(1),third.leaseId,{...result,status:'needs_review'});
 assert.equal((await a.getCached(user(2),digest(1))).status,'needs_review');
 assert.equal((await marker.getOrReserve(user(1),digest(1))).state,'reserved','comparison allowance does not corrupt marker records');
 clock+=86400000;
 const next=await a.getOrReserve(user(1),digest(4));clock+=300001;
 await assert.rejects(a.finish(user(1),digest(4),next.leaseId,result),e=>e.code==='marking_lease_lost');
 console.log('comparison store tests passed: isolated CAS jobs, quotas, privacy, failures and expired leases');
})().catch(e=>{console.error(e);process.exitCode=1});
