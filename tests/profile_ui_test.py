"""Profile uploads use local images and a mocked account endpoint only."""
import os,json,base64
from playwright.sync_api import sync_playwright
photo=''
requests=[]
def auth(route):
    global photo
    data=route.request.post_data_json
    action=data['action']
    if action=='profile':
        photo=data['photo'];requests.append(photo)
        result={'ok':True,'photo':photo}
    elif action=='load':result={'data':{},'revisions':{},'photo':photo}
    else:result={'ok':True,'data':{'u':{}},'revisions':{}}
    route.fulfill(json=result)
with sync_playwright() as p:
    browser=p.chromium.launch(**({'executable_path':os.environ['CHROME']} if os.environ.get('CHROME') else {}))
    page=browser.new_page()
    page.route('**/api/auth',auth)
    page.route('**/api/class',lambda r:r.fulfill(json={'configured':False,'member':False}))
    page.route('https://**/*',lambda r:r.abort())
    page.goto(os.environ['SITE'])
    page.evaluate("replaceState({tok:'mock',ae:'photo@education.nsw.gov.au',owner:'photo@education.nsw.gov.au'});location.hash='#/account'")
    page.wait_for_selector('#profile-file',state='attached')
    # A real PNG generated by browser canvas exercises decoding, cropping and JPEG conversion.
    png=page.evaluate("(()=>{let c=document.createElement('canvas');c.width=64;c.height=32;let x=c.getContext('2d');x.fillStyle='red';x.fillRect(0,0,64,32);return c.toDataURL('image/png').split(',')[1]})()")
    with page.expect_file_chooser() as picker:
        page.click('[data-act=photo-upload]')
    picker.value.set_files({'name':'photo.png','mimeType':'image/png','buffer':base64.b64decode(png)})
    page.wait_for_function("document.querySelector('#photo-status').textContent==='Picture saved.'")
    assert photo.startswith('data:image/jpeg;base64,') and len(photo)<44000
    assert page.locator('#profile-preview img').count()==1
    page.reload();page.wait_for_selector('#profile-preview img')
    page.click('[data-act=photo-remove]')
    page.wait_for_function("document.querySelector('#photo-status').textContent==='Picture removed.'")
    assert photo=='' and page.locator('#profile-preview img').count()==0
    page.evaluate("photoRead(new File(['bad'],'bad.svg',{type:'image/svg+xml'}))")
    assert 'Choose a JPEG' in page.inner_text('#photo-status')
    assert len(requests)==2
    page.evaluate("replaceState({});render()")
    assert page.evaluate("S.photo")==''
    browser.close()
print('PROFILE UI OK: image conversion, upload, reload, removal, invalid files and sign-out isolation')
